/** Resolve a reserved role to the method set it executes today. */
export function selectedSkillRoleKey(role) {
  return SELECTED_SKILL_ROLE_ALIASES[role] ?? role
}

/** One entry per catalog name; a missing row is a catalog/provider drift, not an empty list. */
export function selectedSkillRouting(name) {
  return SELECTED_SKILL_ROUTING[name]
}

/** Catalog entries a role may load. Callers still apply the enabled selection. */
export function selectedSkillNamesForRole(role, catalog) {
  const key = selectedSkillRoleKey(role)
  return catalog.filter((entry) => SELECTED_SKILL_ROUTING[entry.name]?.roles.includes(key)).map((entry) => entry.name)
}

/** Trigger text used by the host catalog, the role prompt and the card. */
export function selectedSkillUseWhen(name, locale = 'zh') {
  const routing = SELECTED_SKILL_ROUTING[name]
  return routing?.useWhen[locale] ?? routing?.useWhen.zh ?? ''
}
